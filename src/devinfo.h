#pragma once
// Подсказки разработчика: на что смотрит камера и переход по координатам.
//
// Зачем: породы (Р77, Р78) видно только там, где камень открыт, и на глаз их не отличить -
// «не увидел разницы» было про это. Пока в окне нет вывода текста, подсказка идёт в заголовок
// окна, туда же, где кадровая сводка.
#include <string>

#include <glm/vec3.hpp>

namespace world {
struct TerrainParams;
}

namespace dev {

/** Что под прицелом: имя материала, координаты блока и расстояние. Пусто - в пределах дальности ничего. */
struct Aim {
    bool hit = false;
    std::string name;          // «гранодиорит», «дёрн», «вода»...
    glm::ivec3 block{};        // блок мира (не воксель)
    float distance = 0;        // блоки
    std::string detail;        // для породы - главные минералы состава
};

/**
 * Луч из камеры тем же кодом, которым строится мир: высоты столбца, материал по формуле и пещеры.
 * Отвечает ровно то, что нарисовано, включая пустоту в шахте. Считается дорого (столбцы генерации),
 * поэтому зовётся редко - раз в полсекунды, вместе с обновлением заголовка.
 *
 * eye и дальность - в блоках; yaw и pitch - как у камеры в main.
 */
Aim aimedAt(const world::TerrainParams& p, glm::vec3 eye, float yaw, float pitch, float maxBlocks);

/** Разбор строки перехода: «x z» (высота - над рельефом) или «x y z». false - не разобралось. */
bool parseGoto(const std::string& s, glm::vec3& out, bool& hasY);

/** Высота поверхности в точке (блоки) - чтобы переход по «x z» не ставил под землю. */
float groundAt(const world::TerrainParams& p, float x, float z);

}  // namespace dev
