#pragma once
// Фиксированная точка Q16.16 (Р16): число хранится как int32, младшие 16 бит - дробная часть.
// 1.0 = 65536. Сложение и вычитание - как у целых; умножение - через 64 бита и сдвиг обратно.
// Одинаковый результат до бита на любой машине: никакой плавающей точки в генерации.
#include <cstdint>

namespace fx {

using q16 = int32_t;
constexpr int SHIFT = 16;
constexpr q16 ONE = 1 << SHIFT;

// a·b: произведение двух Q16 - это Q32, сдвигом возвращаем в Q16. Сдвиг вправо у отрицательных в C++20
// определён как арифметический (округление к минус бесконечности) - одинаково на всех компиляторах.
constexpr q16 mul(q16 a, q16 b) { return static_cast<q16>((static_cast<int64_t>(a) * b) >> SHIFT); }

// линейное смешивание a..b по t ∈ [0, 1]
constexpr q16 lerp(q16 a, q16 b, q16 t) { return a + mul(t, b - a); }

// Сглаживание Перлина 6t⁵ − 15t⁴ + 10t³ (схема Горнера: t³·(t·(6t − 15) + 10)).
// Первая и вторая производные в 0 и 1 равны нулю - на рёбрах ячеек нет изломов и «швов» освещения.
constexpr q16 fade(q16 t) {
    q16 inner = mul(t, mul(t, 6 * ONE) - 15 * ONE) + 10 * ONE;
    return mul(mul(mul(t, t), t), inner);
}

}  // namespace fx
