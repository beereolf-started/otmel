#pragma once
// Рисование строк дебаг-меню в картинку средствами системы (GDI).
//
// Зачем своим кодом: сторонних библиотек шрифта в проекте нет, тащить их ради отладочной панели
// незачем, а кириллицу надо показывать как есть. Windows умеет нарисовать текст системным
// моноширинным шрифтом сам; мы берём готовые точки и отдаём их отрисовке одной картинкой.
//
// Панель перерисовывается только когда строки изменились - это дешевле, чем атлас букв, и
// заметно проще: ни метрик, ни раскладки глифов.
#include <cstdint>
#include <string>
#include <vector>

namespace dev {

/** Картинка панели: RGBA, строки сверху вниз. */
struct TextImage {
    int w = 0, h = 0;
    std::vector<uint8_t> rgba;
    bool empty() const { return w <= 0 || h <= 0; }
};

/**
 * Нарисовать строки: светлые буквы на полупрозрачной тёмной подложке, моноширинный шрифт.
 * Строки - в UTF-8. false - не вышло (нет шрифта, не та система).
 */
bool renderLines(const std::vector<std::string>& lines, int fontPx, TextImage& out);

}  // namespace dev
