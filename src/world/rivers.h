#pragma once
// Реки и озёра (Р29, Р30). Местной формулой (Р2), без глобального прохода:
//   - узлы сетки через 2^RIVER_CELL_LOG2 вокселей (2048 блоков), каждый сдвинут хешем в своей клетке;
//   - в узле - потенциал стока: сглаженная высота рельефа (без форм мельче 2 км: материк, плато, массивы цепей)
//     плюс уклон к морю (материковость · 200 блоков) - мелкие впадины не рвут сток на бассейны-лужицы;
//   - узел стекает в самого низкого из 8 соседей, если тот строго ниже - только вниз, без циклов по построению;
//     все соседи выше - котловина, там озеро; узел ниже уровня моря - море, там река кончается;
//   - полноводность A - сколько узлов окна 17×17 стекают в этот (не дальше 16 звеньев): от порядка счёта не
//     зависит; ширина, глубина русла и радиус долины растут как √A;
//   - Р30: уровень воды в точке реки - минимум земли (исходный рельеф) на ВСЁМ пути выше по течению, со всеми
//     притоками, минус блок. Только вниз и никогда не выше земли на линии реки - по построению; где земля после
//     ложбины снова растёт, река прорезает подъём ущельем; где земля обрывается - уровень падает ступенью
//     (водопад), где спускается полого - пологий сход. Считается по дереву стока вверх до истоков - точно,
//     запоминается на узел.
// Рельеф меняется маской: в русле - дно чашей, пойма, стенки долины, к краю долины - исходный рельеф;
// долина только прорезает, кроме вала у берега (держит воду там, где земля ниже реки).
#include <cstdint>
#include <vector>

#include "world/terrain.h"

namespace world {

constexpr int RIVER_CELL_LOG2 = 15;

// Узел стока - для проверок и карты
struct RiverNode {
    int64_t px, pz;     // положение, воксели
    int32_t smooth;     // потенциал стока: сглаженная высота + уклон к морю, воксели
    bool sea;           // ниже уровня моря - река здесь кончается
    int down;           // в какого соседа стекает: 0..7, -1 - никуда (котловина или море)
    int32_t area;       // полноводность A, узлов
    int32_t level;      // уровень воды в узле (Р30), воксели
    int32_t outEnd;     // уровень воды в конце вытекающего звена (у соседа ниже), воксели
};
RiverNode riverNode(const TerrainParams& p, int32_t i, int32_t j);
void riverNeighbor(int32_t i, int32_t j, int dir, int32_t& ni, int32_t& nj);

// Звенья рек и озёра, задевающие прямоугольник, - собираются один раз на кусок или плитку
struct RiverSet {
    static constexpr int32_t RUN_STEP = 16 * VOXELS_PER_BLOCK;   // шаг точек уровня вдоль звена
    struct Seg {
        int64_t ax, az, bx, bz;     // от узла к соседу ниже по течению; у озера a = b - центр
        int64_t len;                // длина звена, воксели (у озера 0)
        int32_t half, depth, valley;   // полуширина русла (у озера - радиус), глубина, радиус долины; воксели
        // уровень воды вдоль звена - через RUN_STEP от начала (минимум земли на пути выше, минус блок);
        // у озера - одно число
        std::vector<int32_t> run;
    };
    std::vector<Seg> segs;
    void build(const TerrainParams& p, int32_t x0, int32_t z0, int32_t x1, int32_t z1);
    // Рельеф и вода столбца с учётом рек: h - высота дна (меняется), water - уровень воды (поднимается),
    // shore - у воды (берег, дно русла)
    void apply(const TerrainParams& p, int32_t x, int32_t z, int32_t& h, int32_t& water, bool& shore) const;
};

}  // namespace world
