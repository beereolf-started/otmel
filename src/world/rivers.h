#pragma once
// Реки и озёра (Р29-Р32). Местной формулой (Р2), без глобального прохода:
//   - узлы сетки через 2^RIVER_CELL_LOG2 вокселей (2048 блоков), каждый сдвинут хешем в своей клетке;
//   - в узле - потенциал стока: сглаженная высота рельефа (без форм мельче 2 км: материк, плато, массивы цепей)
//     плюс уклон к морю (материковость · 200 блоков) - мелкие впадины не рвут сток на бассейны-лужицы;
//   - узел стекает в самого низкого из 8 соседей, если тот строго ниже - только вниз, без циклов по построению;
//     все соседи выше - котловина, там озеро; узел ниже уровня моря - море, там река кончается;
//   - полноводность A - сколько узлов окна 33×33 стекают в этот (не дальше 32 звеньев, Р36): от порядка счёта не
//     зависит; ширина, глубина русла и радиус долины растут как √A;
//   - Р30: уровень воды в точке реки - минимум земли (исходный рельеф) на ВСЁМ пути выше по течению, со всеми
//     притоками, минус блок. Только вниз и никогда не выше земли на линии реки - по построению; где земля после
//     ложбины снова растёт, река прорезает подъём ущельем; где земля обрывается - уровень падает ступенью
//     (водопад), где спускается полого - пологий сход. Считается по дереву стока вверх до истоков - точно,
//     запоминается на узел.
//   - Р32: русло - явная ломаная, проложенная низом (см. RiverPath); уровень - по ней же, ступенями в блок.
// Рельеф меняется маской: в русле - дно чашей, пойма, стенки долины, к краю долины - исходный рельеф;
// долина только прорезает (Р32: вала нет; русло над чужой долиной ниже его воды - сухое, вода сливается).
#include <cstdint>
#include <memory>
#include <vector>

#include "world/terrain.h"

namespace world {

constexpr int RIVER_CELL_LOG2 = 15;

// Узел стока - для проверок и карты
struct RiverNode {
    int64_t px, pz;     // положение, воксели
    int32_t smooth;     // потенциал стока: сглаженная высота + уклон к морю, воксели
    bool sea;           // ниже уровня моря - река здесь кончается
    int down;           // в какого соседа стекает: 0..7, -1 - никуда (котловина или море)
    int32_t area;       // полноводность A, узлов
    int32_t level;      // уровень воды в узле (Р30), воксели
    int32_t outEnd;     // уровень воды в конце вытекающего звена (у соседа ниже), воксели
};
RiverNode riverNode(const TerrainParams& p, int32_t i, int32_t j);
void riverNeighbor(int32_t i, int32_t j, int dir, int32_t& ni, int32_t& nj);

// Р32: русло звена - явная ломаная от узла к узлу ниже. Строится один раз на узел: поиск ложбины (река идёт
// низом в коридоре ±400 блоков от прямой), сверху - меандры, затем сглаживание. Уровень считается по этой же
// ломаной - вода не выше земли там, где она действительно течёт.
struct RiverPath {
    struct Box { int64_t x0, z0, x1, z1; };
    std::vector<int64_t> x, z;      // вершины, воксели
    std::vector<int64_t> cum;       // путь от начала до вершины, воксели
    std::vector<int32_t> run;       // уровень в вершине: минимум земли на пути выше, минус блок (Р30)
    std::vector<int32_t> wq;        // Р35: ширина русла в вершине, доля (Q16); пусто - везде полная
    std::vector<Box> boxes;         // рамки групп по GROUP рёбер - быстрый поиск ближайших рёбер
    std::vector<Box> supers;        // рамки по SUPER групп - далёкие участки отбрасываются одной проверкой
    std::vector<int32_t> boxLow, superLow;   // нижний уровень воды в группе и в блоке групп
    Box bounds{};
    int64_t len = 0;
    static constexpr int GROUP = 4, SUPER = 16;
};

// Звенья рек и озёра, задевающие прямоугольник, - собираются один раз на кусок или плитку
struct RiverSet {
    struct Seg {
        std::shared_ptr<const RiverPath> path;   // у озера - одна вершина (центр) и один уровень
        int64_t len;                // длина по руслу, воксели (у озера 0)
        int32_t half, depth, valley;   // полуширина русла (у озера - радиус), глубина, радиус долины; воксели
        int32_t area;               // полноводность A
        int32_t minLevel;           // нижний уровень воды на рёбрах у прямоугольника (для грубой отсечки)
        int32_t gFirst, gLast;      // Р32: группы рёбер, которые могут дотянуться до прямоугольника
    };
    std::vector<Seg> segs;
    // Р31: шумы рек (ширина, глубина, пойма, берега, бугры, рукава) - в узлах глобальной сетки через
    // 8 вокселей, между ними линейно (как медленные поля, Р22): на кусок 36 узлов вместо 1156 точек; узлы
    // глобальные - значение в точке не зависит от того, кто спросил (шва нет); вершины плиток стоят на узлах
    enum Noise { N_WIDTH, N_DEPTH, N_PLAIN, N_BANK, N_EDGE, N_BANKL, N_BED, N_B1, N_B2, N_BRAID, N_WX2, N_WZ2,
                 N_COUNT };
    struct NoiseNode { fx::q16 v[N_COUNT]; };
    std::vector<NoiseNode> grid;
    int32_t gnx0 = 0, gnz0 = 0, gw = 0, gh = 0;
    void noiseAt(const TerrainParams& p, int32_t x, int32_t z, fx::q16 out[N_COUNT]) const;
    // Р32: уровень воды в точке u звена (воксели по руслу от начала): ступенями в блок - плёсы и перекаты
    static int32_t levelAlong(const Seg& g, int64_t u);
    // Р31: течение в точке: направление вдоль русла (единичный вектор, Q16), скорость (блоки/с, Q16)
    struct Current { fx::q16 dirX, dirZ, speed; bool inRiver; };
    Current current(const TerrainParams& p, int32_t x, int32_t z) const;
    void build(const TerrainParams& p, int32_t x0, int32_t z0, int32_t x1, int32_t z1);
    // Рельеф и вода столбца с учётом рек: h - высота дна (меняется), water - уровень воды (поднимается),
    // shore - у воды (берег, дно русла)
    void apply(const TerrainParams& p, int32_t x, int32_t z, int32_t& h, int32_t& water, bool& shore) const;
};

}  // namespace world
