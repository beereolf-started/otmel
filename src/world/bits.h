#pragma once
#include <cstdint>

namespace world {

// ─── Поворот битовой таблицы 32×32 (Р18) ──────────────────────────────────────
// a[r], бит c - клетка (строка r, столбец c). После поворота a[c], бит r - та же клетка: строки стали
// столбцами. Вместо 1024 переносов по биту - 5 проходов: меняем местами блоки 16×16, потом 8×8 внутри
// них, 4×4, 2×2, 1×1; каждый проход - сдвиги и маски над целыми 32-битными строками (Hacker's Delight, 7-3).
inline void transpose32(uint32_t a[32]) {
    uint32_t m = 0x0000FFFFu;
    for (int j = 16; j != 0; j >>= 1, m ^= (m << j)) {
        for (int k = 0; k < 32; k = (k + j + 1) & ~j) {
            const uint32_t t = ((a[k] >> j) ^ a[k + j]) & m;
            a[k] ^= t << j;
            a[k + j] ^= t;
        }
    }
}

}  // namespace world
