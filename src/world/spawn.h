// по настоящему верху столбца - с учётом воды и среза.
#include "world/terrain.h"

namespace world {

struct Spawn {
    double x = 0, z = 0;    // блоки мира
    double ground = 0;      // верх твёрдого грунта, блоки
    bool moved = false;     // пришлось отойти от желаемой точки
    bool dry = true;        // нашлась суша (иначе - вода, ставим над ней)
};

// Ближайшая к (wantX, wantZ) суша не дальше maxBlocks; если её нет - сама точка над водой.
Spawn findSpawn(const TerrainParams& p, double wantX, double wantZ, double maxBlocks = 65536.0);

}  // namespace world
