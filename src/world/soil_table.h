#pragma once
// Р87: СПРАВОЧНИК ПОЧВ - состав и приближение ближайшим именем.
//
// Устроен так же, как справочник пород (Р78), и по той же причине. Генератор считает состав почвы
// в точке НЕПРЕРЫВНО - по дождям, теплу, крутизне и материнской породе, - а наружу отдаёт
// БЛИЖАЙШЕЕ ИМЯ отсюда. Поэтому переход от песка к глине идёт не смесью двух, а чередой
// именованных почв: супесь, суглинок, пылеватый суглинок, глинистый суглинок.
//
// Состав - четыре доли, в сумме единица: песок (крупное зерно), пыль, глина, перегной.
#include <cstdint>

namespace world {

/** Доли состава почвы; сумма равна единице. */
struct SoilComp {
    float sand, silt, clay, organic;
};

struct SoilDef {
    const char* name;    // по-русски, как видит игрок
    SoilComp comp;
    const char* tex;     // образец в сборке (tools/atlas.py), пока текстуры чужие
};

/** Сколько именованных почв. Номер почвы попадает в материал - порядок неизменен. */
constexpr int SOIL_COUNT = 9;

const SoilDef& soilDef(int soil);

/** Ближайшее имя к составу - по расстоянию в том же пространстве долей. */
int nearestSoil(const SoilComp& c);

}  // namespace world
