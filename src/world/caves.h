#pragma once
// Пещеры (Р26). Плотность пещер - максимум из двух каналов, воздух - где канал больше нуля:
//   тоннели («спагетти»): t² - (a² + b²), где a и b - два 3D-симплекса; близки к нулю оба сразу - вдоль
//     линии пересечения двух поверхностей, т.е. по извилистой трубе. По высоте шум сжат вдвое - ходы пологие;
//   залы: шум «сыра» выше порога, не ближе hallDepth к поверхности; ниже giantTop - ярус гигантских полостей.
// Узлы - через 8 вокселей (полблока), между узлами - смешивание по трём осям. Смешивание не выходит за
// пределы значений в узлах: если во всех узлах куска каналы <= 0, воздуха в нём нет точно - по вокселям
// не считаем (так отсекается большинство подземных кусков).
// У поверхности (ближе tunnelCover) тоннелей нет, кроме мест, где разрешает 2D-шум входов.
#include <cstdint>

#include "world/chunk.h"
#include "world/terrain.h"

namespace world {

// Воздух пещер в куске С КАЙМОЙ: air[z+1][x+1] - 34 бита по высоте (бит i - воксель y0 - 1 + i), как маски
// сетки (Р18). Ответ false - в куске и кайме воздуха пещер нет вовсе (air тогда не заполняется).
bool caveAir(const TerrainParams& p, ChunkPos pos, const ColumnHeights& hm, uint64_t air[CHUNK + 2][CHUNK + 2]);

// Р39: может ли у столбца кусков (cx, cz) быть вход в пещеру (шум входов у центра - с запасом, как в быстром отказе)
bool caveEntranceNear(const TerrainParams& p, int32_t cx, int32_t cz);

// Р41: устье пещеры у поверхности top в точке (x, z) - для дальних плиток (бурое пятно): вход разрешён и тоннель
// подходит к поверхности. widenBlocks - шаг сетки плитки в блоках: на дальних уровнях тоннель считается толще,
// иначе узкий ход проскакивает между вершинами
bool caveMouth(const TerrainParams& p, int32_t x, int32_t z, int32_t top, int32_t widenBlocks);

}  // namespace world
