#pragma once
// Р53: дуб-коряга - процедурный граф ветвей в вокселях (Р12: деревья - графы, не столбы).
//   - Р57: дуб 8-9 блоков, молодой: ствол - тонкий ясный столб (удобно рубить), крона круглая и плотная;
//   - скелет: ствол (порядок 0) низкий, наверху делится на 2-3 сука (1), от них ветви (2) и веточки (3); каждая
//     ветвь растёт шагами, направление на шаге: d' = norm(d + κ·блуждание + φ·вверх - σ·провисание) - κ даёт
//     корявость, φ - тягу к свету, σ - провисание длинных сучьев; обломанные сучки-пеньки;
//   - корни: 4-6 от комля наружу и вниз, ветвятся, уходят в землю (флаг root - можно не рисовать под землёй);
//   - толщина - правило Леонардо: r^2.5 родителя = сумма r^2.5 детей (от кончиков к комлю), комель расширен;
//   - воксели: каждое ребро - усечённый конус, радиус гуляет 3D-шумом (наплывы); снаружи кора, внутри древесина;
//     листва - комки у кончиков веточек, прорезанные шумом (просветы).
// Координаты - МЕЛКИЕ воксели (Р56: 1/16 блока мира, тексель) от основания ствола (0, 0, 0), y вверх: дуб ~200
// мелких вокселей. Одно семя - всегда одно и то же дерево.
#include <cstdint>
#include <vector>

#include "world/chunk.h"

namespace world {

struct OakVoxels {
    int scale = 1;                    // Р63: размер вокселя в мелких вокселях (1, 2, 4, 8, 16 = блок)
    int32_t x0 = 0, y0 = 0, z0 = 0;   // угол рамки от основания ствола, в вокселях своего размера
    int sx = 0, sy = 0, sz = 0;       // размер рамки
    std::vector<Material> v;          // [(y·sz + z)·sx + x]; AIR - пусто
    std::vector<uint8_t> root;        // 1 - воксель корня
    int nodes = 0, wood = 0, leaves = 0, roots = 0;
    int top = 0;                      // верх дерева от основания, мелкие воксели
    Material at(int x, int y, int z) const { return v[(size_t(y) * sz + z) * sx + x]; }
};

// Р63: scale - уровень детализации: один и тот же скелет, воксели крупнее в scale раз (цена - в scale³ меньше);
// ветки тоньше трети вокселя не рисуются, листва крупнее 2 мелких вокселей - сплошными комками
void growOak(uint32_t seed, OakVoxels& out, int scale = 1);

}  // namespace world
