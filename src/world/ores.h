#pragma once
// Р88: РУДЫ - ВКЛЮЧЕНИЯ В ПОРОДЕ.
//
// Руда у нас не отдельный блок «руда», а порода с вкраплениями: рудное тело - это область, внутри
// которой часть вокселей заменена рудным минералом, а остальное осталось породой-хозяином.
//
// Глубина НЕ задаётся поясами (решение Р76): руда там, где её создал процесс, а процесс привязан к
// породе вокруг и к тому, насколько глубоко под поверхностью мы находимся.
//
//   россыпи и зона окисления - первые десятки метров: малахит, лимонит, гематит;
//   осадочные - в своих пластах: уголь и лигнит, гипс, каменная соль, сера;
//   гидротермальные и порфировые - у кислых глубинных пород: халькопирит, галенит, сфалерит,
//     золото в кварце, касситерит, висмутин;
//   магматические - внутри основных пород: магнетит, гарниерит, самородная медь;
//   метаморфические - графит, пирит.
//
// Тело - ячейка 48 блоков: в части ячеек заводится шар случайного радиуса от двух до девяти блоков.
// Отсюда и разброс богатства: от единичного вокселя, который можно пропустить, до большой залежи.
#include <cstdint>

#include "world/chunk.h"

namespace world {

constexpr int ORE_COUNT = 20;

struct OreDef {
    const char* name;   // по-русски, как видит игрок
    const char* tex;    // накладка из сборки (tools/atlas.py), пока текстуры чужие
};
const OreDef& oreDef(int ore);

// Рудный минерал вокселя или AIR, если здесь чистая порода.
//   host    - порода-хозяин (материал ROCK_FIRST..ROCK_LAST);
//   surface - верх столбца, воксели: от него считается глубина.
Material oreAt(uint32_t seed, int32_t x, int32_t y, int32_t z, Material host, int32_t surface);

}  // namespace world
