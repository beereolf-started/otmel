#pragma once
// Р89: РУДА - ЖИЛЫ, А НЕ РОССЫПЬ ПЫЛИ.
//
// Жила - продолговатое ИЗОГНУТОЕ тело: ось - дуга длиной 40..130 блоков, сечение - сплюснутый
// эллипс 3..9 блоков, край рваный от трёхмерного шума. Это не меньше жил TFG (там 15..45 блоков).
// Внутри жилы у каждой точки есть БОГАТСТВО: у края ноль, к сердцевине до единицы. По нему решается,
// что лежит в блоке породы: в сердцевине - самородок размером в блок, ближе к краю - куски мельче,
// вплоть до одного мелкого вокселя (1/16 блока).
//
// Куски строятся ТОЛЬКО в открытых блоках - в стенке шахты, обрыве, пещере - и садятся на открытую
// грань, торча из неё. Внутри сплошного камня строить нечего: его не видно. Отсюда же: сломал блок -
// его руда ушла вместе с ним, а на открывшихся гранях соседей проступила их руда.
//
// Минерал один на жилу в данной породе (по жребию жилы), плюс спутник: четверть кусков - второй
// минерал. Что за минералы, решают порода вокруг и глубина под поверхностью (Р76: поясов нет).
#include <cstdint>
#include <vector>

#include "world/chunk.h"

namespace world {

constexpr int ORE_COUNT = 20;
// У каждого минерала НЕ ОДИН цвет, а палитра: тёмный, основной и блестящий оттенки (Р88).
constexpr int ORE_SHADES = 3;
constexpr int FINE = 16;   // мелких вокселей в блоке

struct OreDef {
    const char* name;   // по-русски, как видит игрок
};
const OreDef& oreDef(int ore);

/** Кусок руды: СЕРЕДИНА в мелких вокселях (абсолютно) и полуоси неправильного тельца (Р88). */
struct OreSpeck {
    int32_t x, y, z;
    uint8_t a, b, c;   // полуоси в мелких вокселях: a вдоль dir, b поперёк, c по вертикали
    uint8_t dir;       // направление вытянутости, 0..15 по кругу
    uint32_t roll;     // жребий куска: по нему рвётся край
};

/** Жила: дуга с центром c, осью d, изгибом bend (поперёк оси), сечением R × R·flat. Блоки. */
struct Vein {
    float c[3], d[3], n1[3], n2[3], bend[3];
    float half, R, flat;
    uint32_t seed, roll, roll2;
    float reach;   // радиус шара, в который жила вписана
};

/** Все жилы, задевающие куб блоков [b0, b0 + side). */
void veinsNear(uint32_t seed, int32_t bx, int32_t by, int32_t bz, int side, std::vector<Vein>& out);

/** Богатство жилы в блоке (x, y, z): 0 - вне жилы, к сердцевине до 1. */
float veinRichness(const Vein& v, int32_t x, int32_t y, int32_t z);

/** Какой минерал даёт жила с этим жребием в такой породе на такой глубине (блоки под поверхностью). */
int pickOre(Material host, int32_t depth, uint32_t roll);

}  // namespace world
