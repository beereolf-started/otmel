#pragma once
// Р88 (переделано): РУДА - МЕЛКИЕ ВОКСЕЛИ ВНУТРИ КАМНЯ.
//
// Это существенное отличие от TFG, и оно записано в дневнике с самого начала: руда у нас не блок
// «руда с вкраплениями», а настоящие тела в объёме. Вкрапление - мелкий воксель в одну шестнадцатую
// блока, тот же размер, на котором живут деревья. Оно может лежать посреди блока, может
// перехлёстывать через стык двух блоков - блочной сетке руда не подчиняется вовсе. Размер от
// одного мелкого вокселя до самородка в несколько кубов.
//
// Распределение СЛОИСТОЕ, а не случайный крап: вкрапления садятся на плоскости напластования и
// выстраиваются тонкими прожилками вдоль слоёв. Так их кладёт настоящая геология, и так они
// читаются в обрыве.
//
// Текстур у руды нет - только палитра: цвет минерала.
#include <cstdint>
#include <vector>

#include "world/chunk.h"

namespace world {

constexpr int ORE_COUNT = 20;
constexpr int FINE = 16;   // мелких вокселей в блоке

struct OreDef {
    const char* name;   // по-русски, как видит игрок
};
const OreDef& oreDef(int ore);

/** Вкрапление: положение в МЕЛКИХ вокселях (абсолютно), сторона кубика и жребий своего тела. */
struct OreSpeck {
    int32_t x, y, z;
    uint8_t size;   // мелких вокселей по стороне: 1 - крупинка, 8 - полблока
    uint32_t roll;  // жребий тела: по нему и по породе-хозяину выбирается минерал
};

/** Все вкрапления, задевающие куб блоков [b0, b0 + side). */
void oreSpecks(uint32_t seed, int32_t bx, int32_t by, int32_t bz, int side, std::vector<OreSpeck>& out);

/** Какой минерал даёт это тело в такой породе на такой глубине (блоки под поверхностью). */
int pickOre(Material host, int32_t depth, uint32_t roll);

}  // namespace world
