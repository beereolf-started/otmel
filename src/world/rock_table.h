#pragma once
// Р78: СПРАВОЧНИК ПОРОД - состав и приближение ближайшим именем.
//
// У каждой именованной породы записан состав: доли минералов плюс два свойства сложения -
// зернистость и сланцеватость. Это справочник, а не расчёт: ничего во время игры не
// пересчитывается, состав только читается (им порода названа, его же показываем игроку).
//
// Генератор считает состав в точке НЕПРЕРЫВНО (тип района, слой разреза, близость интрузии) и
// приближает его БЛИЖАЙШИМ ИМЕНЕМ отсюда. Поэтому плавное изменение состава по местности выходит
// не смесью двух пород, а чередой именованных: между гранитом и диоритом лежит гранодиорит,
// между известняком и аргиллитом - мергель. Переход аппроксимируется дискретно.
//
// Набор содержит весь набор TFC/TFG целиком (первые ROCK_TFG штук, порядок неизменен - номер
// попадает в материал и в сохранения) и промежуточные между ними.
#include <cstdint>

namespace world {

/** Минералы состава. Доли в сумме дают единицу. */
enum Mineral : uint8_t { QUARTZ, FELDSPAR, MICA, MAFIC, CALCITE, DOLOMITE_M, CLAY, ORGANIC, MINERALS };

/**
 * Состав породы: доли минералов и сложение.
 *   grain  - зернистость: 0 стекло и афанит, 1 крупнокристаллическая;
 *   fabric - сланцеватость: 0 массивная, 1 расслоённая в плитку.
 */
struct Composition {
    float m[MINERALS];
    float grain, fabric;
};

/** Семейство: приближение не выходит за семейства тех пород, между которыми идёт переход. */
enum Family : uint8_t { F_DEEP = 1, F_LAVA = 2, F_SEDIMENT = 4, F_META = 8 };

struct RockDef {
    const char* name;        // по-русски, как видит игрок
    uint8_t family;
    Composition comp;
};

/** Сколько пород пришло из TFC/TFG - они первые в перечне Rock и своих номеров не меняют. */
constexpr int ROCK_TFG = 20;

/** Справочник: описание породы по её номеру (world::Rock). */
const RockDef& rockDef(int rock);

/**
 * Ближайшее имя к составу: по взвешенному расстоянию в том же пространстве. families - маска
 * разрешённых семейств: между двумя осадочными не должен вылезать мрамор, даже если состав сошёлся.
 */
int nearestRock(const Composition& c, uint8_t families = 0xFF);

/** Состав между двумя породами: доля w второй. Нужна генератору, чтобы было что приближать. */
Composition mixComp(const Composition& a, const Composition& b, float w);

}  // namespace world
