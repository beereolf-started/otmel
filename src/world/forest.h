// Р65: лес - часть генерации, одна формула на всех расстояниях (Р62): вблизи - дубы уровнями детализации (Р63),
// дальше - спрайты, ещё дальше - шум крон на земле дальних плиток. Все три берут места, семена и густоту отсюда.
//   - ячейки по FOREST_CELL блоков; хеш ячейки (и зерна мира) даёт кандидата - блок в ячейке, сдвиг в мелких
//     вокселях (0..15, не центр блока), семя дуба и бросок 0..1;
//   - густота - гладкая ступень дождей (0.05..0.5 доли) × шум рощ (ячейка 512 блоков: рощи, перелески, поляны) ×
//     0.85; в снегу - 0. Дерево стоит, если бросок < густоты (и место годится: не вода, не круто - проверяет тот,
//     кто знает рельеф).
#include <cstdint>
#include <vector>

#include "world/terrain.h"

namespace world {

constexpr int FOREST_CELL = 10;   // блоков

struct TreeCandidate {
    int32_t x, z;      // блок
    int fx, fz;        // сдвиг ствола в мелких вокселях внутри блока
    uint32_t seed;     // семя дуба
    float roll;        // бросок 0..1 (дерево - если меньше густоты)
};
TreeCandidate forestCandidate(const TerrainParams& p, int32_t ci, int32_t cj);

// густота леса 0..1 в точке (блоки) с высотой земли h (воксели = блоки, Р54)
float forestDensity(const TerrainParams& p, int32_t x, int32_t z, int32_t h);
float forestDensity(const TerrainParams& p, int32_t x, int32_t z, int32_t h, const Climate& cl);

// Р74: спрайты дубов - по областям 256×256 блоков, точно на ту землю, что видна:
//   в зоне вокселей - высота и вода мира (реки собраны на область: 4-6 мкс на точку вместо 200), вода и крутизна в
//     7×7 у ствола (выборки через 3 блока); низ - по меньшей из высот 2×2 (как у дубов вблизи);
//   за зоной - поверхность плитки своего уровня: узлы через 16·2^L блоков, те же октавы (до 2^(L+5)), тот же
//     треугольник (диагональ (i, j)-(i+1, j+1)); вода хоть в одном узле треугольника - дерева нет;
//   дальнее кольцо (за 1.6 км) - только чётные ячейки (четверть деревьев, спрайт шире ×1.6).
// Раньше: земля - поле течений (клетка 16 блоков) или крупный рельеф без рек и без проверки воды - дальние спрайты
// стояли в руслах и висели над прорезанными долинами, ближние тонули до 16 блоков.
constexpr int SPRITE_REGION = 256;
struct SpriteRegion { int mode = -1; std::vector<float> inst; };
// вид области: exact - в зоне вокселей; even - дальнее кольцо; level - уровень плиток (за зоной)
inline int spriteMode(bool exact, bool even, int level) { return (even ? 1 << 8 : 0) | (exact ? 0xFF : level); }
// спрайты области (rx, rz): по 8 чисел - x, y, z основания (прежние меры), высота, ширина, семя, 0, 0
std::vector<float> buildSpriteRegion(const TerrainParams& p, int rx, int rz, int mode);

}  // namespace world
